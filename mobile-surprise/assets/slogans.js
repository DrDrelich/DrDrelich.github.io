  var reduceMotion = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  function randInt(n) {
    if (window.Common) return window.Common.randInt(n);
    return Math.floor(Math.random() * n);
  }
  function rot(x, y, deg) {
    var r = deg * Math.PI / 180, c = Math.cos(r), s = Math.sin(r);
    return [x * c - y * s, x * s + y * c];
  }
  function pad(i) { return (i < 10 ? '0' : '') + i; }
  function px(v) { return 'calc(' + (Math.round(v * 100) / 100) + ' * var(--u))'; }
  function maskFromPoly(w, h, nums) {
    var n = nums.split(' '), d = 'M' + n[0] + ' ' + n[1];
    for (var i = 2; i < n.length; i += 2) d += 'L' + n[i] + ' ' + n[i + 1];
    var svg = '<svg xmlns="http://www.w3.org/2000/svg" width="' + w + '" height="' + h + '" viewBox="0 0 ' + w + ' ' + h +
      '" preserveAspectRatio="none"><path d="' + d + 'Z"/></svg>';
    return 'url("data:image/svg+xml,' + encodeURIComponent(svg) + '")';
  }

