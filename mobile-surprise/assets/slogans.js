  function Slogan(el, key) {
    var self = this;
    this.el = el; this.key = key;
    this.home = TILES[key];
    this.cur = this.home.slice();
    this.last = -1;
    var v = V[key];
    el.innerHTML = '';
    el.style.width = px(v.w);
    el.style.height = px(v.h);
    el.setAttribute('role', 'img');
    el.setAttribute('aria-label', 'Surprise Yourself!');

    this.slots = this.home.map(function (t) {
      var p = document.createElement('span');
      p.className = 'sl-tile';
      var g = document.createElement('span');
      g.className = 'glyph';
      p.appendChild(g);
      el.appendChild(p);
      return { p: p, g: g, cx: t.cx, cy: t.cy, tapes: [] };
    });
    this.tapeLayer = document.createElement('span');
    this.tapeLayer.className = 'tapes';
    el.appendChild(this.tapeLayer);
    var ul = document.createElement('img');
    ul.className = 'underline';
    ul.alt = '';
    ul.src = IMG + 'underline.svg';
    ul.style.left = px(v.ul[0] - 257.76 / 2);
    ul.style.top = px(v.ul[1] - 10.734 / 2);
    ul.style.width = px(257.76);
    ul.style.height = px(10.734);
    el.appendChild(ul);

    this.slots.forEach(function (s, i) { self.apply(i, self.home[i], false); });
    if (!reduceMotion) this.start();
  }

  Slogan.prototype.apply = function (i, t, fadeTapes) {
    var s = this.slots[i], p = s.p, g = s.g, f = FONT[t.font];
    p.style.left = px(s.cx - t.w / 2);
    p.style.top = px(s.cy - t.h / 2);
    p.style.width = px(t.w);
    p.style.height = px(t.h);
    p.style.transform = 'rotate(' + t.a + 'deg)';
    p.style.backgroundImage = 'url(' + t.tex + ')';
    p.style.webkitMaskImage = t.mask;
    p.style.maskImage = t.mask;
    g.textContent = t.ch;
    g.style.fontFamily = f[0];
    g.style.fontWeight = f[1];
    g.style.fontSize = px(t.size);
    g.style.color = t.color;
    g.style.left = 'calc(50% + ' + (Math.round(t.gx * 100) / 100) + ' * var(--u))';
    g.style.top = 'calc(50% + ' + (Math.round(t.gy * 100) / 100) + ' * var(--u))';

    var layer = this.tapeLayer;
    s.tapes.forEach(function (el) { el.remove(); });
    s.tapes = t.tapes.map(function (tp) {
      var c = rot(tp.x, tp.y, t.a);
      var el = document.createElement('span');
      el.className = 'tape';
      el.style.left = px(s.cx + c[0] - tp.w / 2);
      el.style.top = px(s.cy + c[1] - tp.h / 2);
      el.style.width = px(tp.w);
      el.style.height = px(tp.h);
      el.style.transform = 'rotate(' + (t.a + tp.ra) + 'deg)';
      layer.appendChild(el);
      if (fadeTapes && el.animate) el.animate([{ opacity: 0 }, { opacity: 1 }], { duration: 180, delay: 90, fill: 'backwards' });
      return el;
    });
  };

  // Swap one random letter for the same letter from another variant.
  Slogan.prototype.swapOne = function () {
    var n = this.slots.length, i;
    do { i = randInt(n); } while (i === this.last);
    this.last = i;
    var cur = this.cur[i], home = this.home[i];
    var next;
    if (cur !== home && randInt(100) < 45) next = home;          // drift back to this screen's design
    else {
      var pool = ALL.filter(function (t) { return t.ch === cur.ch && t !== cur; });
      next = pool[randInt(pool.length)];
    }
    this.cur[i] = next;
    var self = this, s = this.slots[i], p = s.p, a0 = cur.a, a1 = next.a;
    s.tapes.forEach(function (el) {
      if (el.animate) el.animate([{ opacity: 1 }, { opacity: 0 }], { duration: 120, fill: 'forwards' });
    });
    if (!p.animate) { this.apply(i, next, false); return; }
    var out = p.animate([
      { transform: 'rotate(' + a0 + 'deg) scale(1, 1)' },
      { transform: 'rotate(' + a0 + 'deg) scale(0.04, 1.06)' }
    ], { duration: 130, easing: 'cubic-bezier(.5,0,1,.6)', fill: 'forwards' });
    out.onfinish = function () {
      self.apply(i, next, true);
      p.animate([
        { transform: 'rotate(' + a1 + 'deg) scale(0.04, 1.06)' },
        { transform: 'rotate(' + a1 + 'deg) scale(1.1, 1.1)', offset: 0.6 },
        { transform: 'rotate(' + a1 + 'deg) scale(1, 1)' }
      ], { duration: 240, easing: 'cubic-bezier(.2,.8,.3,1)' });
      out.cancel();
    };
  };

  Slogan.prototype.start = function () {
    var self = this;
    function next(delay) {
      self.timer = setTimeout(function () {
        // only while the page is visible and this slogan is on screen
        if (document.visibilityState === 'visible' && self.el.offsetParent !== null) self.swapOne();
        next(600 + randInt(700));
      }, delay);
    }
    next(1000 + randInt(500));   // screen-load animations start 1 s in
  };
  Slogan.prototype.stop = function () { clearTimeout(this.timer); };

  window.Slogan = Slogan;
  window.SLOGAN_TILES = TILES;
